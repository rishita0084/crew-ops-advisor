"""Record real engine responses as the frontend's offline fixtures.

The console ships with mock data so it can run standalone. Hand-written mocks drift
from the real contract and, worse, invent crew and pairings that do not exist. These
fixtures are recorded from the live deterministic engine instead, so offline mode shows
the same facts the backend would return.

    python scripts/record_fixtures.py
"""
from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.alerts.sentinel import build_alerts  # noqa: E402
